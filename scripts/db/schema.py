"""How a project-tracker database is created.

One path: an empty database is built from schema.sql (generated by
schema_dump.py from create_database + every migration), and the
`schema_migrations` ledger is marked for the migrations it contains. Every
later change is a numbered migration in migrations/, applied by
`pt db migrate` after a verified backup. Nothing here alters an existing
database.

SAFETY POLICY - READ BEFORE MODIFYING:
--------------------------------------
1. NEVER use DROP TABLE on tables that may contain data
2. NEVER use DELETE FROM without explicit user confirmation
3. Schema changes are numbered migrations applied by `pt db migrate` after a
   verified backup; rebuilding or dropping a table needs the DB gate
4. If schema is incompatible, REFUSE and print instructions - don't auto-fix
5. Any destructive operation requires:
   - Explicit backup first
   - User confirmation
   - Audit log entry

This policy exists because we lost 94 tasks on 2026-01-27 due to an
auto-migration that dropped tables without backup.
"""

import os
import sqlite3
import sys
import uuid
from datetime import UTC, datetime
from pathlib import Path

# Add parent directory to path for config import
PROJECT_ROOT = Path(__file__).parent.parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

try:
    from scripts.config import DATABASE_PATH
except ImportError:
    # Fallback for when scripts/config.py is not in path (e.g. during some test setups)
    DATABASE_PATH = Path("data/tracker.db")

# The schema a fresh database is created from (generated by schema_dump.py)
# and the migrations that bring every database up to date.
SCHEMA_SQL = Path(__file__).with_name("schema.sql")
MIGRATIONS_DIR = Path(__file__).with_name("migrations")


class SafetyError(Exception):
    """Raised when a destructive operation is blocked by safety policy."""



class FreshDatabaseError(Exception):
    """Raised when we detect a fresh database where we expected data."""


def _mark_data_location(db_path: Path) -> None:
    """Leave the marker _check_fresh_database looks for: a database with data lives here.

    It sits outside the database on purpose. If the file is later replaced by
    an empty one, the marker remains and the guard refuses to treat the empty
    file as new. Only its existence matters; an existing marker is kept.
    """
    marker = db_path.parent / ".db-fingerprint"
    if not marker.exists():
        marker.write_text(str(uuid.uuid4()))


def _check_fresh_database(db_path: Path) -> None:
    """Check if database looks unexpectedly fresh.
    
    If tasks table exists but is empty, and we're not in test mode,
    this is suspicious - the database may have been replaced.
    """
    # Skip check in test environments
    if os.getenv("PT_TEST_MODE") == "1" or os.getenv("PT_ALLOW_FRESH_DB") == "1":
        return
    
    # Skip check if pytest is running
    if "pytest" in sys.modules:
        return
    
    try:
        with sqlite3.connect(db_path) as conn:
            cursor = conn.cursor()
            
            # Check if tasks table exists
            cursor.execute("SELECT name FROM sqlite_master WHERE type='table' AND name='tasks'")
            if not cursor.fetchone():
                return  # No tasks table yet - this is a truly new database
            
            # Check task and project counts
            cursor.execute("SELECT COUNT(*) FROM tasks")
            task_count = cursor.fetchone()[0]
            cursor.execute("SELECT COUNT(*) FROM projects")
            project_count = cursor.fetchone()[0]

            history_count = 0
            cursor.execute("SELECT name FROM sqlite_master WHERE type='table' AND name='task_history'")
            if cursor.fetchone():
                cursor.execute("SELECT COUNT(*) FROM task_history")
                history_count = cursor.fetchone()[0]

            delete_audit_count = 0
            cursor.execute("SELECT name FROM sqlite_master WHERE type='table' AND name='delete_audit_log'")
            if cursor.fetchone():
                cursor.execute("SELECT COUNT(*) FROM delete_audit_log")
                delete_audit_count = cursor.fetchone()[0]
        
        if task_count == 0:
            # Check if fingerprint file exists - if so, we expected data!
            fingerprint_path = db_path.parent / ".db-fingerprint"
            if fingerprint_path.exists() and project_count == 0:
                raise FreshDatabaseError(
                    f"⛔ UNEXPECTED FRESH DATABASE DETECTED!\n"
                    f"   Database has tasks table but 0 tasks and 0 projects.\n"
                    f"   Fingerprint file exists - we expected existing data.\n"
                    f"   This suggests the database file was replaced.\n"
                    f"\n"
                    f"   To proceed anyway: PT_ALLOW_FRESH_DB=1 pt <command>\n"
                    f"   To restore: check data/backups/ or ~/.project-tracker/backups/\n"
                    f"\n"
                    f"   If you emptied it on purpose: delete {fingerprint_path} and try again."
                )

            backup_dir = db_path.parent / "backups"
            prior_task_backups = list(backup_dir.glob("tasks_*.json")) if backup_dir.exists() else []
            suspicious_missing_tasks = history_count > 0 or (bool(prior_task_backups) and delete_audit_count == 0)

            if fingerprint_path.exists() and project_count > 0 and suspicious_missing_tasks:
                raise FreshDatabaseError(
                    f"⛔ SUSPICIOUS EMPTY TASK BOARD DETECTED!\n"
                    f"   Database has 0 tasks but {project_count} projects.\n"
                    f"   Prior task activity exists without a matching delete trail.\n"
                    f"   This suggests tasks may have been wiped while project metadata survived.\n"
                    f"\n"
                    f"   To proceed anyway: PT_ALLOW_FRESH_DB=1 pt <command>\n"
                    f"   To restore: check data/backups/ or ~/.project-tracker/backups/"
                )
    except FreshDatabaseError:
        raise
    except Exception as e:
        # Don't block startup for check errors - just warn
        print(f"⚠️  Warning: Could not check database freshness: {e}")


def get_db_path() -> Path:
    """Get the database file path."""
    env_path = os.getenv("PT_DB_PATH")
    return Path(env_path) if env_path else DATABASE_PATH



def has_legacy_crsql_triggers(db_path: Path) -> bool:
    """True if the database still carries `__crsql_` triggers (pre-migration 018).

    Such triggers call cr-sqlite functions, which no connection loads any more,
    so every write to the affected tables fails with "no such function:
    crsql_internal_sync_bit". Reads are unaffected. A missing file reports
    False; any other error (unreadable or corrupt file) propagates.
    """
    from contextlib import closing

    db_path = Path(db_path)
    if not db_path.exists():
        return False
    uri = db_path.resolve().as_uri() + "?mode=ro"
    with closing(sqlite3.connect(uri, uri=True)) as conn:
        return conn.execute(
            "SELECT 1 FROM sqlite_master WHERE type='trigger' "
            "AND name LIKE '%\\_\\_crsql\\_%' ESCAPE '\\' LIMIT 1"
        ).fetchone() is not None




def _user_tables(conn: sqlite3.Connection) -> set[str]:
    return {row[0] for row in conn.execute(
        "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
    )}


def _schema_sql_version(text: str) -> int:
    """The last migration schema.sql contains, from its generated header."""
    for line in text.splitlines():
        if line.startswith("-- Migrations: through "):
            return int(line.rsplit(" ", 1)[1])
    raise RuntimeError(f"{SCHEMA_SQL} has no '-- Migrations: through NNN' header; regenerate it")


def create_database(db_path: Path | None = None) -> None:
    """Create a LOCAL SQLite database from schema.sql, or leave an existing one alone.

    There is one creation path. An empty database gets schema.sql (generated
    by schema_dump.py) in one transaction, and the migration ledger is marked
    for every migration the file already contains; newer migrations then
    apply through `pt db migrate` like on any other database. An existing
    database is never changed here: its migrations are `pt db migrate`'s job.
    The fresh-database guard's marker is left the first time an existing
    database holds a project or a task, not at creation: an install's own new,
    empty database must not look like a replaced one.

    A non-empty database without the `schema_migrations` ledger predates the
    migration runner. Upgrading it would mean replaying table rebuilds over
    real data, so it is refused instead (restore a newer backup).
    """
    from .migration_runner import discover_migrations

    if db_path is None:
        db_path = get_db_path()

    # SAFETY: Check for unexpected fresh database
    if db_path.exists():
        _check_fresh_database(db_path)

    conn = sqlite3.connect(db_path, isolation_level=None)
    try:
        tables = _user_tables(conn)
        if tables:
            if "schema_migrations" not in tables:
                raise SafetyError(
                    f"{db_path} has tables but no schema_migrations ledger: it predates "
                    "the migration runner (April 2026) and cannot be upgraded in place. "
                    "Restore a newer backup (`pt backup list`)."
                )
            if conn.execute(
                "SELECT EXISTS (SELECT 1 FROM projects) OR EXISTS (SELECT 1 FROM tasks)"
            ).fetchone()[0]:
                _mark_data_location(db_path)
            return

        schema = SCHEMA_SQL.read_text()
        version = _schema_sql_version(schema)
        statements = _statements(schema)
        contained = [m for m in discover_migrations(MIGRATIONS_DIR, verbose=False) if m.version <= version]
        missing = sorted(set(range(2, version + 1)) - {m.version for m in contained})
        if missing:
            raise RuntimeError(f"schema.sql contains migrations {missing} that are not in {MIGRATIONS_DIR}")
        now = datetime.now(UTC)
        conn.execute("BEGIN IMMEDIATE")
        try:
            if _user_tables(conn):
                # Another process built it while we waited for the write lock.
                conn.execute("ROLLBACK")
                return
            for statement in statements:
                conn.execute(statement)
            conn.executemany(
                "INSERT INTO schema_migrations (version, name, applied_at) VALUES (?, ?, ?)",
                [(m.version, m.name, now.isoformat(timespec="seconds")) for m in contained],
            )
            conn.execute("COMMIT")
        except BaseException:
            if conn.in_transaction:
                conn.execute("ROLLBACK")
            raise
    finally:
        conn.close()


def schema_statements() -> list[str]:
    """schema.sql as executable statements (for building a schema in memory)."""
    return _statements(SCHEMA_SQL.read_text())


def _statements(script: str) -> list[str]:
    """Split schema.sql into complete statements (trigger bodies contain ';')."""
    statements, current = [], ""
    for line in script.splitlines(keepends=True):
        if not current and (not line.strip() or line.startswith("--")):
            continue
        current += line
        if sqlite3.complete_statement(current):
            statements.append(current.strip())
            current = ""
    if current.strip():
        raise RuntimeError(f"{SCHEMA_SQL} ends with an incomplete statement")
    return statements


def init_db() -> Path:
    """Initialize database if it doesn't exist."""
    db_path = get_db_path()
    create_database(db_path)
    return db_path


if __name__ == "__main__":
    # For testing
    db_path = init_db()
    print(f"Database created at: {db_path}")
